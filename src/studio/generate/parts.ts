import type { Clip, Note, Project, Track, TrackOrigin } from "@/studio/types";
import { generateBass, type PartNote } from "./bass";
import { chordPart, generateChords } from "./chords";
import { generateDrums } from "./drums";
import { melodyOf, planFor, type Plan } from "./plan";
import { defaultStyle, type Style } from "./style";

type Part = Extract<TrackOrigin, { kind: "generated" }>["part"];

/** What each generated part sounds like and where it sits. */
const parts: Record<Part, Pick<Track, "name" | "type" | "color" | "instrumentPreset" | "volume">> = {
  chords: { name: "Chords", type: "midi", color: "keys", instrumentPreset: "warm-pad", volume: 0.55 },
  bass: { name: "Bass", type: "midi", color: "bass", instrumentPreset: "synth-bass", volume: 0.7 },
  drums: { name: "Drums", type: "drum", color: "drums", instrumentPreset: "hum-drums", volume: 0.75 },
};

const isGenerated = (t: Track) => t.origin?.kind === "generated";

/** A part Claude wrote, which is kept as written until the songwriter asks for it to be rewritten. */
export const isClaudePart = (t: Track) => t.origin?.kind === "generated" && t.origin.by === "claude";

/**
 * Writes chords, bass and drums for the arrangement's melody as ordinary tracks marked as generated by rules. Running it
 * again rewrites the generated tracks' notes, keeping their mixer settings; the melody and anything added by hand stay as
 * they are. Parts Claude wrote are replaced too, unless `keepClaudeParts` is set: Style changes and Directions keep them.
 */
export function withGeneratedParts(project: Project, { keepClaudeParts = false } = {}): Project {
  const plan = planFor(project);
  const melody = melodyOf(project);
  // Chords and bass follow a melody, so there are none without one. A hummed beat is the drums, so none are generated over it.
  const chords = melody.length ? generateChords(plan, melody) : [];
  const hummedBeat = project.tracks.some((t) => t.origin?.kind === "hum" && t.type === "drum");
  const written: Record<Part, Note[]> = {
    chords: chordPart(plan, chords).map(note),
    bass: chords.length ? generateBass(plan, chords).map(note) : [],
    drums: hummedBeat ? [] : generateDrums(plan).map(note),
  };

  const previous = (part: Part) => project.tracks.find((t) => t.origin?.kind === "generated" && t.origin.part === part);
  const keep = (t: Track) => !isGenerated(t) || (keepClaudeParts && isClaudePart(t));
  const kept = project.tracks.filter(keep);
  const claudeWrote = new Set(kept.flatMap((t) => (t.origin?.kind === "generated" ? [t.origin.part] : [])));
  const keptIds = new Set(kept.map((t) => t.id));
  const tracks = [...kept];
  const clips = project.clips.filter((c) => keptIds.has(c.trackId));
  let order = Math.max(-1, ...kept.map((t) => t.order));

  for (const part of Object.keys(parts) as Part[]) {
    if (!written[part].length || claudeWrote.has(part)) continue;
    const track: Track = previous(part) ?? {
      ...parts[part],
      id: crypto.randomUUID(),
      projectId: project.id,
      pan: 0,
      muted: false,
      solo: false,
      armed: false,
      order: 0,
    };
    tracks.push({ ...track, order: ++order, origin: { kind: "generated", part, by: "rules" } });
    clips.push(clipFor(track, plan, written[part]));
  }
  return { ...project, tracks, clips };
}

function clipFor(track: Track, plan: Plan, notes: Note[]): Clip {
  return {
    id: crypto.randomUUID(),
    trackId: track.id,
    type: track.type === "drum" ? "drum" : "midi",
    name: track.name,
    startBar: 0,
    lengthBars: plan.bars,
    notes,
  };
}

function note(n: PartNote): Note {
  return { id: crypto.randomUUID(), ...n };
}

/**
 * The arrangement in a new Style. Rule-written parts are rewritten to follow it straight away, and parts Claude wrote
 * are kept as written; before anything has been generated, the Style is just kept for the next Generate parts.
 */
export function withStyle(project: Project, changes: Partial<Style>): Project {
  const styled = { ...project, style: { ...(project.style ?? defaultStyle), ...changes } };
  return project.tracks.some(isGenerated) ? withGeneratedParts(styled, { keepClaudeParts: true }) : styled;
}
